// BuildScript 生成 k6 脚本（DES-T-001：参数白名单 + 模板转义，无用户 JS 拼接）。
//
// 校验点：
//   - 并发数/档位 VU 必须为正整数且 ≤ maxVUs（否则 ErrInvalidConcurrency → 23004）；
//   - 时长走白名单正则；
//   - 接口地址必须为 http/https 且不含空白/控制字符；
//   - 接口方法限定在 GET/POST/PUT/PATCH/DELETE/HEAD。
func BuildScript(spec ScriptSpec) (string, error) {
	params, err := spec.Flow.Params(spec.MaxVUs)
	if err != nil {
		return "", err
	}
	steps, err := spec.Flow.ValidateSteps()
	if err != nil {
		return "", err
	}
	testMode := spec.Flow.TestModeValue()
	if testMode != domain.TestModeFlow && testMode != domain.TestModeSingle {
		return "", fmt.Errorf("测试模式非法")
	}

	view := scriptView{
		Mode:                params.Mode,
		TestMode:            testMode,
		VUs:                 params.VUs,
		DurationText:        params.DurationText,
		TimeoutText:         params.TimeoutText,
		ThinkTimeSeconds:    params.ThinkTime.Seconds(),
		CaptureResponseBody: spec.Flow.CaptureResponseBody,
		VarPattern:          `\{\{\s*([A-Za-z0-9_]+)\s*\}\}`,
		Requests:            make([]scriptRequest, 0, len(spec.Interfaces)),
	}
	for _, st := range params.Stages {
		view.Stages = append(view.Stages, scriptStage{DurationText: st.Duration.String(), VUs: st.VUs})
	}
	if params.Mode == domain.ConcurrencyModePulse {
		view.Stages = pulseStages(params.VUs, params.Duration)
	}

	tmpl := scriptTmpl
	if testMode == domain.TestModeFlow {
		setupSteps, mainSteps, preSteps, err := buildFlowSteps(steps, spec.Interfaces, spec.TargetHost)
		if err != nil {
			return "", err
		}
		view.SetupSteps, view.MainSteps, view.PreSteps = setupSteps, mainSteps, preSteps
		tmpl = flowTmpl
	} else {
		if len(spec.Interfaces) == 0 {
			return "", fmt.Errorf("接口范围为空")
		}
		for i := range spec.Interfaces {
			req, err := buildRequest(&spec.Interfaces[i], spec.TargetHost)
			if err != nil {
				return "", err
			}
			view.Requests = append(view.Requests, *req)
		}
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, view); err != nil {
		return "", fmt.Errorf("渲染 k6 脚本失败: %w", err)
	}
	return buf.String(), nil
}

// buildFlowSteps 把流程步骤解析为模板步骤（按作用域分桶），并合并步骤级请求覆盖。
func buildFlowSteps(steps []domain.FlowStep, interfaces []domain.InterfaceSnapshot, targetHost string) (setupSteps, mainSteps, preSteps []scriptStep, err error) {
	byID := make(map[int64]*domain.InterfaceSnapshot, len(interfaces))
	for i := range interfaces {
		byID[interfaces[i].InterfaceID] = &interfaces[i]
	}
	for _, st := range steps {
		snap, ok := byID[st.InterfaceID]
		if !ok {
			return nil, nil, nil, fmt.Errorf("步骤引用的接口不在任务接口范围内")
		}
		// 步骤级路径覆盖：以接口快照为基础，只替换 path（地址仍由 target_host 拼接）。
		if strings.TrimSpace(st.Path) != "" {
			override := *snap
			override.Path = st.Path
			override.URL = ""
			snap = &override
		}
		req, err := buildRequest(snap, targetHost)
		if err != nil {
			return nil, nil, nil, err
		}
		body := req.Body
		if strings.TrimSpace(st.Body) != "" {
			body = st.Body
		}
		headers := req.Headers
		if len(st.Headers) > 0 {
			headers, err = mergeHeaders(req.Headers, st.Headers)
			if err != nil {
				return nil, nil, nil, err
			}
		}
		extractJSON := "[]"
		if len(st.Extract) > 0 {
			raw, err := json.Marshal(st.Extract)
			if err != nil {
				return nil, nil, nil, fmt.Errorf("序列化提取规则失败: %w", err)
			}
			extractJSON = string(raw)
		}
		label := fmt.Sprintf("第 %d 步", st.Seq)
		if name := strings.TrimSpace(st.Name); name != "" {
			label = fmt.Sprintf("第 %d 步（%s）", st.Seq, name)
		}
		item := scriptStep{
			Method:          req.Method,
			URL:             req.URL,
			Headers:         headers,
			Body:            body,
			InterfaceIDText: req.InterfaceIDText,
			ExtractJSON:     extractJSON,
			Label:           label,
		}
		switch st.Scope {
		case domain.ScopeOncePerTest:
			setupSteps = append(setupSteps, item)
		case domain.ScopeEveryRequest:
			preSteps = append(preSteps, item)
		default:
			mainSteps = append(mainSteps, item)
		}
	}
	if len(mainSteps) == 0 {
		return nil, nil, nil, fmt.Errorf("流程测试至少需要一个主流程步骤")
	}
	return setupSteps, mainSteps, preSteps, nil
}

// mergeHeaders 合并快照请求头与步骤级覆盖（后者优先）。
func mergeHeaders(baseJSON string, overrides map[string]string) (string, error) {
	headers := map[string]string{}
	if strings.TrimSpace(baseJSON) != "" {
		if err := json.Unmarshal([]byte(baseJSON), &headers); err != nil {
			return "", fmt.Errorf("请求头解析失败: %w", err)
		}
	}
	for name, value := range overrides {
		headers[name] = value
	}
	raw, err := json.Marshal(headers)
	if err != nil {
		return "", fmt.Errorf("序列化请求头失败: %w", err)
	}
	return string(raw), nil
}

// buildRequest 校验并构建模板请求（URL/方法/请求头/请求体白名单）。
func buildRequest(snap *domain.InterfaceSnapshot, targetHost string) (*scriptRequest, error) {
	rawURL, err := interfaceURL(snap, targetHost)
	if err != nil {
		return nil, err
	}

	method := strings.ToUpper(strings.TrimSpace(snap.Method))
	switch method {
	case domain.MethodGet, domain.MethodPost, domain.MethodPut, domain.MethodPatch,
		domain.MethodDelete, "HEAD":
	default:
		return nil, fmt.Errorf("接口方法非法")
	}

	body := snap.Body
	if len(body) > maxRequestBody {
		return nil, fmt.Errorf("接口请求体过大")
	}

	headers := snap.Headers
	if headers == nil {
		headers = map[string]string{}
	}
	// 认证头明文不进入快照/脚本：脚本仅携带普通请求头（凭据由 k6 运行环境注入）。
	rawHeaders, err := json.Marshal(headers)
	if err != nil {
		return nil, fmt.Errorf("序列化请求头失败: %w", err)
	}
	return &scriptRequest{
		Method:          method,
		URL:             rawURL,
		Headers:         string(rawHeaders),
		Body:            body,
		InterfaceIDText: strconv.FormatInt(snap.InterfaceID, 10),
	}, nil
}

// interfaceURL 生成单接口的完整压测地址。
//
// 新口径：{scheme}://{target_host}:{port}{path}（接口不配置 host）；
// 兼容口径：迁移前创建的任务快照只有完整 url，原样使用并做同等白名单校验。
func interfaceURL(snap *domain.InterfaceSnapshot, targetHost string) (string, error) {
	if path := strings.TrimSpace(snap.Path); path != "" {
		rawURL, err := domain.InterfaceURL(snap.Scheme, targetHost, snap.Port, path)
		if err != nil || len(rawURL) > maxURLLen {
			return "", fmt.Errorf("接口地址非法")
		}
		return rawURL, nil
	}

	rawURL := strings.TrimSpace(snap.URL)
	if len(rawURL) == 0 || len(rawURL) > maxURLLen {
		return "", fmt.Errorf("接口地址非法")
	}
	for _, r := range rawURL {
		if r <= 0x20 || r == 0x7f {
			return "", fmt.Errorf("接口地址含非法字符")
		}
	}
	parsed, err := url.Parse(rawURL)
	if err != nil || (parsed.Scheme != "http" && parsed.Scheme != "https") || parsed.Host == "" {
		return "", fmt.Errorf("接口地址必须为 http/https 且包含主机")
	}
	return rawURL, nil
}

// pulseStages 生成脉冲加压档位：升压 → 保持 → 降压 → 静默（四段均分总时长）。
func pulseStages(vus int, total time.Duration) []scriptStage {
	quarter := total / 4
	if quarter < time.Second {
		quarter = time.Second
	}
	return []scriptStage{
		{DurationText: quarter.String(), VUs: vus},
		{DurationText: quarter.String(), VUs: vus},
		{DurationText: quarter.String(), VUs: 0},
		{DurationText: quarter.String(), VUs: 0},
	}
}

// ScriptFileName 任务脚本文件名（仅由任务 ID 派生，不含用户输入）。
func ScriptFileName(taskID int64) string { return fmt.Sprintf("task-%d.js", taskID) }

// ResultFileName 任务结果文件名（仅由任务 ID 派生，不含用户输入）。
func ResultFileName(taskID int64) string { return fmt.Sprintf("task-%d.json", taskID) }
