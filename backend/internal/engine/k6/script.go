package k6

import (
	"bytes"
	"encoding/json"
	"fmt"
	"net/url"
	"strconv"
	"strings"
	"text/template"
	"time"

	"auto_performance/internal/domain"
)

// maxURLLen 接口地址长度上限（与产品管理侧一致）。
const maxURLLen = 2048

// maxRequestBody 单接口请求体上限（保护脚本体积）。
const maxRequestBody = 64 * 1024

// ScriptSpec 脚本生成入参（全部用户可控字段在生成前做白名单校验，DES-T-001）。
type ScriptSpec struct {
	// Flow 流程配置（并发模式/并发数/时长等）。
	Flow domain.FlowConfig
	// Interfaces 接口范围（来自任务创建时的接口快照）。
	Interfaces []domain.InterfaceSnapshot
	// MaxVUs 并发数上限（配置项 k6.max_vus）。
	MaxVUs int
}

// scriptRequest 模板中的单个请求（已通过白名单校验）。
type scriptRequest struct {
	Method  string
	URL     string
	Headers string // JSON 对象字面量（经 json.Marshal，安全）
	Body    string
}

// scriptStage 模板中的加压档位。
type scriptStage struct {
	DurationText string
	VUs          int
}

// scriptView 模板渲染视图（仅含已校验/已转义的数据）。
type scriptView struct {
	Mode             string
	VUs              int
	Stages           []scriptStage
	DurationText     string
	TimeoutText      string
	ThinkTimeSeconds float64
	Requests         []scriptRequest
}

// scriptTemplate k6 脚本模板：变量一律经 js 函数（strconv.Quote）转义，不做原始字符串拼接。
const scriptTemplate = `// Code generated by auto_performance. DO NOT EDIT.
// 本脚本由服务端模板生成，用户输入仅以转义后的字符串字面量出现（DES-T-001）。
import http from 'k6/http';
import { check, sleep } from 'k6';

export const options = {
  // 压测目标常为内网/自签证书环境，默认跳过 TLS 证书校验（性能测试场景标准做法）。
  insecureSkipTLSVerify: true,
  scenarios: {
    default: {
{{- if or (eq .Mode "ramp") (eq .Mode "pulse") }}
      executor: 'ramping-vus',
      startVUs: 0,
      stages: [
{{- range .Stages }}
        { duration: {{ js .DurationText }}, target: {{ .VUs }} },
{{- end }}
      ],
{{- else }}
      executor: 'constant-vus',
      vus: {{ .VUs }},
      duration: {{ js .DurationText }},
{{- end }}
      gracefulStop: '30s',
    },
  },
  thresholds: {},
};

const REQUEST_TIMEOUT = {{ js .TimeoutText }};
const THINK_TIME = {{ .ThinkTimeSeconds }};
const REQUESTS = [
{{- range .Requests }}
  {
    method: {{ js .Method }},
    url: {{ js .URL }},
    headers: {{ .Headers }},
    body: {{ js .Body }},
  },
{{- end }}
];

export default function () {
  for (const req of REQUESTS) {
    const params = { headers: req.headers, timeout: REQUEST_TIMEOUT || undefined };
    let res;
    if (req.method === 'GET') {
      res = http.get(req.url, params);
    } else {
      res = http.request(req.method, req.url, req.body, params);
    }
    check(res, { 'status is 2xx-3xx': (r) => r.status >= 200 && r.status < 400 });
    if (THINK_TIME > 0) {
      sleep(THINK_TIME);
    }
  }
}
`

// scriptTmpl 预编译模板（文本静态，用户数据只经占位符注入）。
var scriptTmpl = template.Must(template.New("k6").
	Funcs(template.FuncMap{
		// js 生成 JS 字符串字面量（转义引号/反斜杠/控制字符/换行）。
		"js": func(s string) string { return strconv.Quote(s) },
	}).
	Parse(scriptTemplate))

// BuildScript 生成 k6 脚本（DES-T-001：参数白名单 + 模板转义，无用户 JS 拼接）。
//
// 校验点：
//   - 并发数/档位 VU 必须为正整数且 ≤ maxVUs（否则 ErrInvalidConcurrency → 23004）；
//   - 时长走白名单正则；
//   - 接口地址必须为 http/https 且不含空白/控制字符；
//   - 接口方法限定在 GET/POST/PUT/PATCH/DELETE/HEAD。
func BuildScript(spec ScriptSpec) (string, error) {
	params, err := spec.Flow.Params(spec.MaxVUs)
	if err != nil {
		return "", err
	}
	if len(spec.Interfaces) == 0 {
		return "", fmt.Errorf("接口范围为空")
	}

	view := scriptView{
		Mode:             params.Mode,
		VUs:              params.VUs,
		DurationText:     params.DurationText,
		TimeoutText:      params.TimeoutText,
		ThinkTimeSeconds: params.ThinkTime.Seconds(),
		Requests:         make([]scriptRequest, 0, len(spec.Interfaces)),
	}
	for _, st := range params.Stages {
		view.Stages = append(view.Stages, scriptStage{DurationText: st.Duration.String(), VUs: st.VUs})
	}
	if params.Mode == domain.ConcurrencyModePulse {
		view.Stages = pulseStages(params.VUs, params.Duration)
	}

	for i := range spec.Interfaces {
		req, err := buildRequest(&spec.Interfaces[i])
		if err != nil {
			return "", err
		}
		view.Requests = append(view.Requests, *req)
	}

	var buf bytes.Buffer
	if err := scriptTmpl.Execute(&buf, view); err != nil {
		return "", fmt.Errorf("渲染 k6 脚本失败: %w", err)
	}
	return buf.String(), nil
}

// buildRequest 校验并构建模板请求（URL/方法/请求头/请求体白名单）。
func buildRequest(snap *domain.InterfaceSnapshot) (*scriptRequest, error) {
	rawURL := strings.TrimSpace(snap.URL)
	if len(rawURL) == 0 || len(rawURL) > maxURLLen {
		return nil, fmt.Errorf("接口地址非法")
	}
	for _, r := range rawURL {
		if r <= 0x20 || r == 0x7f {
			return nil, fmt.Errorf("接口地址含非法字符")
		}
	}
	u, err := url.Parse(rawURL)
	if err != nil || (u.Scheme != "http" && u.Scheme != "https") || u.Host == "" {
		return nil, fmt.Errorf("接口地址必须为 http/https 且包含主机")
	}

	method := strings.ToUpper(strings.TrimSpace(snap.Method))
	switch method {
	case domain.MethodGet, domain.MethodPost, domain.MethodPut, domain.MethodPatch,
		domain.MethodDelete, "HEAD":
	default:
		return nil, fmt.Errorf("接口方法非法")
	}

	body := snap.Body
	if len(body) > maxRequestBody {
		return nil, fmt.Errorf("接口请求体过大")
	}

	headers := snap.Headers
	if headers == nil {
		headers = map[string]string{}
	}
	// 认证头明文不进入快照/脚本：脚本仅携带普通请求头（凭据由 k6 运行环境注入）。
	rawHeaders, err := json.Marshal(headers)
	if err != nil {
		return nil, fmt.Errorf("序列化请求头失败: %w", err)
	}
	return &scriptRequest{
		Method:  method,
		URL:     rawURL,
		Headers: string(rawHeaders),
		Body:    body,
	}, nil
}

// pulseStages 生成脉冲加压档位：升压 → 保持 → 降压 → 静默（四段均分总时长）。
func pulseStages(vus int, total time.Duration) []scriptStage {
	quarter := total / 4
	if quarter < time.Second {
		quarter = time.Second
	}
	return []scriptStage{
		{DurationText: quarter.String(), VUs: vus},
		{DurationText: quarter.String(), VUs: vus},
		{DurationText: quarter.String(), VUs: 0},
		{DurationText: quarter.String(), VUs: 0},
	}
}

// ScriptFileName 任务脚本文件名（仅由任务 ID 派生，不含用户输入）。
func ScriptFileName(taskID int64) string { return fmt.Sprintf("task-%d.js", taskID) }

// ResultFileName 任务结果文件名（仅由任务 ID 派生，不含用户输入）。
func ResultFileName(taskID int64) string { return fmt.Sprintf("task-%d.json", taskID) }
