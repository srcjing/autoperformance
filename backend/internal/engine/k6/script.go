// ScriptSpec 脚本生成入参（全部用户可控字段在生成前做白名单校验，DES-T-001）。
type ScriptSpec struct {
	// Flow 流程配置（并发模式/并发数/时长等）。
	Flow domain.FlowConfig
	// Interfaces 接口范围（来自任务创建时的接口快照）。
	Interfaces []domain.InterfaceSnapshot
	// MaxVUs 并发数上限（配置项 k6.max_vus）。
	MaxVUs int
	// TargetHost 压测目标主机（任务的 target_host，来自所选环境 hosts；
	// 接口不再配置 host）。
	TargetHost string
}

// scriptRequest 模板中的单个请求（已通过白名单校验）。
type scriptRequest struct {
	Method  string
	URL     string
	Headers string // JSON 对象字面量（经 json.Marshal，安全）
	Body    string
	// InterfaceIDText 接口 ID 字符串（作为 k6 自定义 tag，支撑请求详情按接口定位）。
	InterfaceIDText string
}

// scriptStep 流程测试中的单个步骤（已校验；headers/extract 均为 JSON 字面量）。
type scriptStep struct {
	Method          string
	URL             string
	Headers         string
	Body            string
	InterfaceIDText string
	ExtractJSON     string
	// Label 步骤标签（如「第 1 步（登录）」），用于变量告警定位。
	Label string
}

// scriptStage 模板中的加压档位。
type scriptStage struct {
	DurationText string
	VUs          int
}

// scriptView 模板渲染视图（仅含已校验/已转义的数据）。
type scriptView struct {
	Mode             string
	VUs              int
	Stages           []scriptStage
	DurationText     string
	TimeoutText      string
	ThinkTimeSeconds float64
	// CaptureResponseBody 是否采集每个请求的响应体（输出 AFREQ 行供服务端落库）。
	CaptureResponseBody bool
	// TestMode single | flow（flow 模式使用 SetupSteps/MainSteps/PreSteps）。
	TestMode string
	// VarPattern 变量占位符正则（由 Go 侧提供 JS 字符串字面量，避免模板中出现区分符）。
	VarPattern string
	Requests   []scriptRequest
	SetupSteps []scriptStep
	MainSteps  []scriptStep
	PreSteps   []scriptStep
}

